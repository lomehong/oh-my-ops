#!/usr/bin/env node
/**
 * embed-pi-natives.mjs — 生成 pi-natives embedded-addon.js（构建管线步骤 3）。
 *
 * 契约（探针实证，见 docs/reports/omo-install-probes.md §H3）：
 *   pi-natives/native/embedded-addon.js 是上游自动生成的占位（embeddedAddon=null），
 *   官方构建由 scripts/embed-native.ts 替换为真实嵌入描述；本脚本复刻该产物：
 *   以 bun 资产导入（`with { type: "file" }`）携带平台 .node，
 *   loader-state.js 经 fs.readFileSync(filePath) 落盘后 require。
 *
 * 用法：
 *   node embed-pi-natives.mjs --natives-dir <pi-natives 包目录> \
 *     --platform-dir <pi-natives-linux-x64 包目录> --platform-tag linux-x64
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

function arg(name) {
	const i = process.argv.indexOf("--" + name);
	return i === -1 ? undefined : process.argv[i + 1];
}

const nativesDir = arg("natives-dir");
const platformDir = arg("platform-dir");
const platformTag = arg("platform-tag");
for (const [k, v] of Object.entries({ "natives-dir": nativesDir, "platform-dir": platformDir, "platform-tag": platformTag })) {
	if (!v) {
		console.error(`✗ --${k} 必填`);
		process.exit(1);
	}
}

const platformPkg = JSON.parse(readFileSync(join(platformDir, "package.json"), "utf8"));
const version = platformPkg.version;

// 收集平台包内全部 .node 文件，按文件名归类 variant
const files = [];
for (const f of readdirSync(platformDir)) {
	if (!f.endsWith(".node")) continue;
	const fp = join(platformDir, f);
	const size = statSync(fp).size;
	const variant = f.includes("modern") ? "modern" : f.includes("baseline") ? "baseline" : "default";
	files.push({ variant, filename: f, size, filePath: f });
}
if (files.length === 0) {
	console.error("✗ 平台目录内未发现 .node 原生件：" + platformDir);
	process.exit(1);
}
files.sort((a, b) => a.filename.localeCompare(b.filename));

// 相对导入路径（native/ → 平台包目录）
const rel = (f) => relative(nativesDir + "/native", join(platformDir, f)).split("\\").join("/");

const header = `// AUTOGENERATED — by oh-my-ops scripts/embed-pi-natives.mjs（复刻上游 scripts/embed-native.ts 产物）
// DO NOT EDIT DIRECTLY。重新构建时由管线覆盖。
`;
const imports = files
	.map((f, i) => `import file${i} from "${rel(f.filePath)}" with { type: "file" };`)
	.join("\n");
const filesOut = files
	.map((f, i) => `\t{ variant: ${JSON.stringify(f.variant)}, filename: ${JSON.stringify(f.filename)}, size: ${f.size}, filePath: file${i} },`)
	.join("\n");

const out = `${header}
/** @typedef {"modern" | "baseline" | "default"} EmbeddedAddonVariant */
${imports}

/** @type {EmbeddedAddon|null} */
export const embeddedAddon = {
	platformTag: ${JSON.stringify(platformTag)},
	version: ${JSON.stringify(version)},
	files: [
${filesOut}
	],
};
export default embeddedAddon;
`;

// emitted 声明供编译器识别资产导入（bun compile 嵌入 .node 用）
const emitted = out;

const dst = join(nativesDir, "native", "embedded-addon.js");
writeFileSync(dst, emitted);
console.log(`  ✓ embedded-addon.js 已生成（platformTag=${platformTag} version=${version} files=${files.length}）→ ${dst}`);
